var _fontWhite = null, _fontBlack = null, _fontMap = null;

function buildFont() {
  if (_fontWhite) return;
  _fontMap = Object.keys(FONT_DATA);
  var w = _fontMap.length * 8;
  _fontWhite = document.createElement("canvas");
  _fontWhite.width = w; _fontWhite.height = 8;
  var ctx = _fontWhite.getContext("2d");
  var img = ctx.createImageData(w, 8);
  for (var g = 0; g < _fontMap.length; g++) {
    var glyph = FONT_DATA[_fontMap[g]];
    for (var y = 0; y < 8; y++) {
      for (var x = 0; x < 8; x++) {
        var on = (glyph[y] >> (7 - x)) & 1;
        var i = ((y * w) + (g * 8 + x)) * 4;
        img.data[i] = 255; img.data[i+1] = 255; img.data[i+2] = 255;
        img.data[i+3] = on ? 255 : 0;
      }
    }
  }
  ctx.putImageData(img, 0, 0);
  _fontBlack = document.createElement("canvas");
  _fontBlack.width = w; _fontBlack.height = 8;
  var bctx = _fontBlack.getContext("2d");
  bctx.drawImage(_fontWhite, 0, 0);
  bctx.globalCompositeOperation = "source-in";
  bctx.fillStyle = "#000";
  bctx.fillRect(0, 0, w, 8);
}

function drawText(ctx, text, x, y) {
  buildFont();
  text = String(text).toUpperCase();
  for (var pass = 0; pass < 2; pass++) {
    var src = pass === 0 ? _fontBlack : _fontWhite;
    var ox = pass === 0 ? 1 : 0, oy = pass === 0 ? 1 : 0;
    for (var i = 0; i < text.length; i++) {
      var gi = _fontMap.indexOf(text[i]);
      if (gi < 0) continue;
      ctx.drawImage(src, gi * 8, 0, 8, 8, x + i * 8 + ox, y + oy, 8, 8);
    }
  }
}
