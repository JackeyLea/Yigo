import { Test, TestingModule } from '@nestjs/testing';
import { JwtService } from '@nestjs/jwt';
import { ConfigService } from '@nestjs/config';
import { DataSource } from 'typeorm';
import { getRepositoryToken } from '@nestjs/typeorm';
import { AuthService } from './auth.service';
import { UserService } from '../user/user.service';
import { User, UserStatus } from '../common/entities/user.entity';
import { Wallet } from '../common/entities/wallet.entity';
import { RegisterDto } from './dto/register.dto';
import { LoginDto } from './dto/login.dto';
import { ConflictException, UnauthorizedException } from '@nestjs/common';
import * as argon2 from 'argon2';
import * as fs from 'fs';
import * as path from 'path';

// Ensure keys exist for tests
const keysDir = './keys';
if (!fs.existsSync(keysDir)) {
  fs.mkdirSync(keysDir, { recursive: true });
}
if (!fs.existsSync(path.join(keysDir, 'jwt-private.pem'))) {
  // Minimal test keys would be generated by setup
}

jest.mock('argon2');

const mockQueryRunner = {
  connect: jest.fn(),
  startTransaction: jest.fn(),
  commitTransaction: jest.fn(),
  rollbackTransaction: jest.fn(),
  release: jest.fn(),
  manager: {
    getRepository: jest.fn(),
    create: jest.fn(),
    save: jest.fn(),
  },
};

const mockDataSource = {
  createQueryRunner: jest.fn().mockReturnValue(mockQueryRunner),
};

const mockUserService = {
  findByUsername: jest.fn(),
  findByUsernameWithPassword: jest.fn(),
  findById: jest.fn(),
  checkEmailExists: jest.fn(),
  userRepository: {
    save: jest.fn(),
  },
};

const mockJwtService = {
  sign: jest.fn().mockReturnValue('mock-jwt-token'),
  verify: jest.fn().mockReturnValue({ sub: '1', username: 'testuser' }),
};

const mockConfigService = {
  get: jest.fn((key: string, defaultValue?: any) => {
    const config: Record<string, any> = {
      JWT_EXPIRATION: '1h',
      JWT_REFRESH_EXPIRATION: '7d',
      JWT_KEYS_DIR: './keys',
    };
    return config[key] ?? defaultValue;
  }),
};

describe('AuthService', () => {
  let service: AuthService;

  beforeEach(async () => {
    jest.clearAllMocks();

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        AuthService,
        { provide: JwtService, useValue: mockJwtService },
        { provide: ConfigService, useValue: mockConfigService },
        { provide: UserService, useValue: mockUserService },
        { provide: DataSource, useValue: mockDataSource },
      ],
    }).compile();

    service = module.get<AuthService>(AuthService);
  });

  describe('hashPassword', () => {
    it('should hash password with argon2id', async () => {
      const password = 'password123';
      (argon2.hash as jest.Mock).mockResolvedValue('hashed-password');

      const result = await service.hashPassword(password);

      expect(argon2.hash).toHaveBeenCalledWith(password, {
        type: argon2.argon2id,
        memoryCost: 65536,
        timeCost: 3,
        parallelism: 4,
      });
      expect(result).toBe('hashed-password');
    });
  });

  describe('verifyPassword', () => {
    it('should verify password with argon2', async () => {
      (argon2.verify as jest.Mock).mockResolvedValue(true);

      const result = await service.verifyPassword('hash', 'password');

      expect(argon2.verify).toHaveBeenCalledWith('hash', 'password');
      expect(result).toBe(true);
    });
  });

  describe('register', () => {
    it('should register a new user successfully', async () => {
      const dto: RegisterDto = {
        username: 'testuser',
        password: 'password123',
        email: 'test@test.com',
      };

      mockUserService.findByUsername.mockResolvedValue(null);
      mockUserService.checkEmailExists.mockResolvedValue(false);
      (argon2.hash as jest.Mock).mockResolvedValue('hashed-password');

      const mockUserRepo = {
        create: jest.fn().mockReturnValue({
          username: dto.username,
          password_hash: 'hashed-password',
          email: dto.email,
          user_id: '1',
        }),
        save: jest.fn().mockResolvedValue({
          user_id: '1',
          username: dto.username,
          email: dto.email,
        }),
      };

      const mockWalletRepo = {
        create: jest.fn().mockReturnValue({
          user_id: '1',
          currency: 'POINT',
        }),
        save: jest.fn().mockResolvedValue({
          wallet_id: '1',
          user_id: '1',
          currency: 'POINT',
        }),
      };

      mockQueryRunner.manager.getRepository.mockImplementation((entity: any) => {
        if (entity === User) return mockUserRepo;
        if (entity === Wallet) return mockWalletRepo;
        return {};
      });

      const result = await service.register(dto);

      expect(result.user_id).toBe('1');
      expect(mockQueryRunner.startTransaction).toHaveBeenCalled();
      expect(mockQueryRunner.commitTransaction).toHaveBeenCalled();
    });

    it('should throw ConflictException if username exists', async () => {
      const dto: RegisterDto = {
        username: 'existing',
        password: 'password123',
      };

      mockUserService.findByUsername.mockResolvedValue({ user_id: '1' } as User);

      await expect(service.register(dto)).rejects.toThrow(ConflictException);
    });
  });

  describe('login', () => {
    it('should login and return tokens', async () => {
      const dto: LoginDto = {
        username: 'testuser',
        password: 'password123',
      };

      const mockUser: Partial<User> = {
        user_id: '1',
        username: 'testuser',
        password_hash: 'hashed',
        nickname: 'Test',
        level: 1,
        status: UserStatus.ACTIVE,
      };

      mockUserService.findByUsernameWithPassword.mockResolvedValue(mockUser);
      (argon2.verify as jest.Mock).mockResolvedValue(true);

      const result = await service.login(dto);

      expect(result.accessToken).toBe('mock-jwt-token');
      expect(result.user.username).toBe('testuser');
    });

    it('should throw UnauthorizedException for invalid credentials', async () => {
      const dto: LoginDto = {
        username: 'testuser',
        password: 'wrong',
      };

      mockUserService.findByUsernameWithPassword.mockResolvedValue(null);

      await expect(service.login(dto)).rejects.toThrow(UnauthorizedException);
    });
  });

  describe('validateUser', () => {
    it('should return user for valid credentials', async () => {
      const mockUser: Partial<User> = {
        user_id: '1',
        username: 'testuser',
        password_hash: 'hashed',
      };

      mockUserService.findByUsernameWithPassword.mockResolvedValue(mockUser);
      (argon2.verify as jest.Mock).mockResolvedValue(true);

      const result = await service.validateUser('testuser', 'password');

      expect(result).toBeDefined();
      expect(result?.username).toBe('testuser');
    });

    it('should return null for invalid credentials', async () => {
      mockUserService.findByUsernameWithPassword.mockResolvedValue(null);

      const result = await service.validateUser('testuser', 'password');

      expect(result).toBeNull();
    });
  });

  describe('refreshToken', () => {
    it('should refresh token successfully', async () => {
      const mockUser: Partial<User> = {
        user_id: '1',
        username: 'testuser',
        nickname: 'Test',
        level: 1,
        status: UserStatus.ACTIVE,
      };

      mockUserService.findById.mockResolvedValue(mockUser);

      const result = await service.refreshToken('valid-refresh-token');

      expect(result.accessToken).toBe('mock-jwt-token');
    });
  });
});
